x = int(input("Введите четырёхзначное число: "))

ths = x // 1000
huns = x // 100 % 10
tens = x // 10 % 10
uns = x % 10

print(f"Цифра в позиции тысяч равна {ths}")
print(f"Цифра в позиции сотен равна {huns}")
print(f"Цифра в позиции десятков равна {tens}")
print(f"Цифра в позиции единиц равна {uns}")